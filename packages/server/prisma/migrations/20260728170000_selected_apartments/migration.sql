-- он снимок момента заявки, ровно как `leads.apartments`, и переписку с тех пор
-- могли почистить.
--
-- NULL, а не пустой массив: у диалогов и лидов, заведённых раньше, выбора не
-- было вовсе, и отличать «не выбирал» от «выбрал ноль» не нужно.
