-- Признак «дом сдан».
--
-- В выгрузках ДомКлик он есть с самого начала и не использовался: у корпуса
-- <building_state>ready</building_state>, у квартиры <ready_housing>1</ready_housing>.
-- Срок сдачи собирался только из built_year и ready_quarter, поэтому 69%
-- каталога — построенные дома — получали «сдачу» в прошлом: Серебро в декабре
-- 2023-го, Космос в июне 2025-го. Клиент видел это рядом с презентацией, где
-- написано «построено, сдано, готово к заселению».
--
-- Колонка отдельная, а не вместо `deadline`: фактическая дата ввода остаётся
-- в базе и никуда не девается, меняется только то, как дом называют.
-- NULL означает «выгрузка о готовности ничего не сказала» — это не то же самое,
-- что «не сдан», и путать их нельзя.
ALTER TABLE "apartments" ADD COLUMN "is_ready" BOOLEAN;
