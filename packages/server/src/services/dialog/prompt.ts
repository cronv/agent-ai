import type { ProjectCategory } from '@prisma/client'

import { PROJECT_CATEGORIES, categoryGenitive, categoryLabel } from '../../lib/categories.js'
import type { CatalogDirection, CatalogLocation } from './apartments.js'
import { millions, plural, roomsLabel } from './wording.js'

/**
 * Сборка системного промпта.
 *
 *   const system = buildSystemPrompt({ basePrompt, projectCount, ... })
 *
 * Постоянная часть — настройка `system_prompt`: её правит администратор
 * в админке, кодом мы её не трогаем. Сюда добавляется только то, чего
 * в настройке быть не может, потому что оно меняется от сообщения к сообщению:
 *
 *   сегодняшняя дата     — иначе «сдача в этом году» модель считает от даты
 *                          обучения и уверенно ошибается на пару лет;
 *   размер каталога      — пустая база знаний должна менять поведение, а не
 *                          порождать выдуманные условия ипотеки;
 *   локации каталога     — без списка модель достаёт географию из общих знаний
 *                          и зовёт клиента в Мытищи, которых у агентства нет;
 *   ход разговора        — правило «не проси контакт раньше времени» работает
 *                          только тогда, когда модель знает, где она сейчас.
 *
 * Перечень локаций — именно перечень, а не намёк: запрет «не выдумывай города»
 * без него нечем исполнить, модели просто не с чем сверяться. Поэтому у каждой
 * локации сразу стоит и то, что в ней есть, — комнатности и вилка цен: тогда
 * альтернатива предлагается по факту, а не наугад.
 */

export interface PromptContext {
  /** Настройка `system_prompt` — характер и правила ассистента. */
  basePrompt: string
  /** Дата, от которой модель считает сроки. */
  today: Date
  /** Сколько активных ЖК в каталоге. */
  projectCount: number
  /** Весь географический охват каталога — см. `listCatalogLocations`. */
  locations: CatalogLocation[]
  /** Направления, которые в каталоге есть, — см. `listCatalogDirections`. */
  directions: CatalogDirection[]
  /** Есть ли что-нибудь в базе знаний. */
  hasKnowledge: boolean
  /** Сколько сообщений написал посетитель за всю переписку. */
  visitorMessages: number
  apartmentsShown: boolean
  /** Сообщений посетителя после последней подборки. */
  messagesSinceApartments: number
  /** Настройка `contact_request_threshold`. */
  contactThreshold: number
  leadCaptured: boolean
  /** Кнопки быстрых ответов включены — значит есть инструмент `suggest_replies`. */
  quickReplies: boolean
  /** Сколько квартир посетитель отметил кнопкой «Выбрать» за диалог. */
  apartmentsChosen: number
}

export function buildSystemPrompt(context: PromptContext): string {
  const lines: string[] = [
    `Сегодня ${formatDate(context.today)}. Сроки сдачи считай от этой даты.`,
    context.projectCount > 0
      ? `В каталоге ${context.projectCount} ${plural(context.projectCount, 'активный ЖК', 'активных ЖК', 'активных ЖК')} — это всё, что ты можешь предлагать.`
      : 'Каталог квартир сейчас пуст: подобрать нечего. Скажи об этом прямо и предложи оставить контакт, чтобы менеджер связался, когда объекты появятся.',
    context.hasKnowledge
      ? 'База знаний загружена: в ней карточки объектов и презентации застройщиков. ' +
        'Всё про конкретный ЖК, кроме цены и комнатности, — адрес, транспорт, окружение, инфраструктура, ' +
        'класс жилья, этажность, паркинг, отделка, сроки, — и всё про ипотеку, рассрочку и акции лежит там. ' +
        'Спросили про названный комплекс — сначала search_knowledge, потом ответ.'
      : 'База знаний пуста: search_knowledge вернёт пустоту по любому запросу. Значит по ипотеке, рассрочке, субсидиям, акциям и отделке у тебя нет ни одной цифры — ни по ЖК, ни «по рынку в целом». Ставки, взносы, лимиты, сроки программ, названия банков и расчёт платежа не называй даже примерно и даже если человек просит приблизительно. Объясни, почему не называешь, скажи что уточнит менеджер, и предложи оставить контакт. Описаний комплексов там тоже нет: про адрес, транспорт, окружение, школы и класс жилья скажи, что этих данных у тебя нет и уточнит менеджер, — из общих знаний о городе их не достраивай.',
    context.visitorMessages === 0
      ? 'Это первое сообщение посетителя.'
      : `Посетитель написал ${context.visitorMessages} ${plural(context.visitorMessages, 'сообщение', 'сообщения', 'сообщений')}.`,
    contactLine(context),
  ]

  const chosen = context.apartmentsChosen
  if (chosen > 0) {
    lines.push(
      `Посетитель отметил кнопкой «Выбрать» ${chosen} ${plural(chosen, 'квартиру', 'квартиры', 'квартир')} — ` +
        'они видны в переписке репликами «Выбрал: …», и менеджеру они уже переданы. ' +
        'Это самый сильный сигнал интереса: дальше говори про выбранное, а не начинай подбор заново.',
    )
  }

  const now = `# Сейчас\n\n${lines.map((line) => `- ${line}`).join('\n')}`
  const kinds = directionsBlock(context.directions)
  const places = locationsBlock(context.locations)
  const buttons = context.quickReplies ? QUICK_REPLIES_BLOCK : ''

  return [context.basePrompt.trim(), now, kinds, places, buttons].filter((part) => part !== '').join('\n\n')
}

/**
 * Направления каталога.
 *
 * Нужен по той же причине, что и перечень локаций: без него «а загородные дома
 * у вас есть?» упирается в общие знания модели, и она отвечает про рынок, а не
 * про агентство. Здесь же прямо сказано, чего у агентства нет, — и отказ
 * получается коротким и честным, без похода в поиск за пустотой.
 */
function directionsBlock(directions: CatalogDirection[]): string {
  if (directions.length === 0) return ''

  const present = new Set(directions.map((item) => item.category))
  const missing = PROJECT_CATEGORIES.filter((category) => !present.has(category))

  const lines = directions.map(
    (item) =>
      `- ${categoryLabel(item.category)}: ${item.projectCount} ${plural(item.projectCount, 'комплекс', 'комплекса', 'комплексов')}, ` +
      `${item.apartmentCount} ${plural(item.apartmentCount, 'объект', 'объекта', 'объектов')} в продаже`,
  )

  const tail: string[] = []
  if (missing.length > 0) {
    tail.push(
      `Ничего другого у агентства нет: ${missing.map(categoryGenitive).join(', ')} в каталоге нет ни одного объекта. ` +
        'Спросили про такое направление — скажи прямо, что этим агентство сейчас не занимается, и предложи то, что есть. ' +
        'Не ищи их поиском: он вернёт квартиры в новостройках и выдаст их за ответ.',
    )
  }
  tail.push(
    'Направления не смешивай: локации и цены ниже относятся к своему направлению и ничего не говорят про остальные.',
  )

  return ['# Направления каталога', '', lines.join('\n'), '', tail.join(' ')].join('\n')
}

/**
 * Правила для кнопок быстрых ответов.
 *
 * Живут в коде, а не в настройке `system_prompt`: настройку правит
 * администратор, и она уже засеяна в боевой базе прежним текстом — дописать
 * туда обязательный технический пункт нечем. Здесь же он появляется ровно
 * тогда, когда включён инструмент, и исчезает вместе с ним.
 *
 * Пункты 7 и 8 — про грамотность надписи. Заказчик получил под ответом
 * «Показать квартиры в школьном», «Сравнить с космосом» и «Покажи еще
 * Пкомплексы»: на трёх словах модель экономит внимание сильнее, чем на трёх
 * абзацах, и ошибка вылезает именно там, где её виднее всего. Одними правилами
 * это не закрывается, поэтому проверяемая часть продублирована на сервере —
 * см. `pickSuggestions` в execute.ts: заглавная буква у названий из каталога
 * восстанавливается, реплика с явно битым словом выбрасывается целиком.
 */
const QUICK_REPLIES_BLOCK = [
  '# Кнопки быстрых ответов',
  '',
  'Под каждым твоим сообщением посетитель видит две–четыре кнопки с готовыми репликами. Их даёшь ты, вызовом suggest_replies.',
  '',
  '1. Кнопки не заменяют ответ и не бывают вместо него. Сначала напиши ответ словами, и только потом, в том же ходу, вызови suggest_replies — одним вызовом, последним действием. Ход, в котором есть вызов и нет текста, посетитель видит как пустое сообщение.',
  '2. Так же и на короткие реплики вроде «Июнь подходит» или «Да». Это не конец разговора, а ответ на твой вопрос: отреагируй словами и веди дальше.',
  '3. Реплики пишутся от лица посетителя и продолжают именно тот ответ, который ты написал. После подборки это «Покажи подешевле», «Другой район», «Хочу посмотреть»; после твоего вопроса — готовые ответы на него, в том числе отказ; после рассказа про условия — следующий разумный вопрос.',
  '4. Коротко: два–четыре слова, без точки в конце. Длинная кнопка не показывается вовсе, и посетитель остаётся без вариантов.',
  '5. Кнопки не отменяют вопрос в тексте. Не пиши «выберите вариант ниже» и не перечисляй варианты словами — они и так под ответом.',
  '6. Не предлагай кнопкой то, чего не сделаешь: «Забронировать», «Скидка», «Точная ставка по ипотеке». Кнопка — это обещание.',
  '7. Надпись на кнопке — законченная русская фраза, написанная грамотно. Букв не пропускай и лишних не ставь: «Покажи ещё комплексы», а не «Покажи еще Пкомплексы». Буква «ё» пишется: «ещё», «трёшка», «её». Перечитай каждую надпись целиком перед вызовом — опечатка в трёх словах заметнее, чем в трёх абзацах, и такую реплику система выбрасывает, оставляя посетителя без кнопки.',
  '8. Названия ЖК, городов и районов пиши так, как они стоят в каталоге: с заглавной буквы и в кавычках. «Показать квартиры в «Школьном»», «Сравнить с «Космосом»», «Другой район, не Подольск» — а не «в школьном», «с космосом» и «в подольске». Название комплекса со строчной буквы читается как обычное слово, и кнопка перестаёт быть понятной.',
  '9. Ни одна кнопка не зовёт в прошлое. Сегодняшняя дата — выше, в разделе «Сейчас»; год в реплике не бывает раньше текущего, а срок — раньше сегодняшнего дня. «Быстрее, в 2024-м» под подборкой со сдачей в 2025-м читается как поломка, и такую реплику система выбрасывает — посетитель остаётся без кнопки. Хочешь предложить срок пораньше — назови ближайший будущий год или обойдись без года вовсе: «Хочу раньше», «Со сдачей в этом году».',
  '',
  'Проверь себя перед отправкой: в ходу есть текст ответа и ровно один вызов suggest_replies. Это относится к каждому ответу без исключения — и к длинному с подборкой, и к двум строчкам про срок сдачи. Ход без вызова оставляет посетителя перед пустым полем ввода.',
].join('\n')

/**
 * Сколько локаций расписывать подробно, а сколько — назвать по имени.
 *
 * Пять локаций на боевых данных, но каталог растёт: сотня районов, расписанных
 * построчно, съест контекст и утопит в себе всё остальное. Подробно идут самые
 * крупные, остальные — просто именами, и этого уже достаточно, чтобы не
 * выдумывать: сверять название есть с чем.
 */
const LOCATIONS_IN_DETAIL = 12
const LOCATIONS_NAMED = 60

function locationsBlock(locations: CatalogLocation[]): string {
  if (locations.length === 0) return ''

  // Локации сгруппированы по направлениям: «Химки» в новостройках и «Химки»
  // в коммерции — разные строки, и человеку, спросившему про квартиру, вторая
  // не подходит. Пока направление одно, заголовок над списком всё равно стоит:
  // он и говорит, к чему относятся эти цифры.
  const byCategory = new Map<ProjectCategory, CatalogLocation[]>()
  for (const place of locations) {
    const list = byCategory.get(place.category) ?? []
    list.push(place)
    byCategory.set(place.category, list)
  }

  const lines: string[] = []
  for (const category of PROJECT_CATEGORIES) {
    const places = byCategory.get(category)
    if (places === undefined || places.length === 0) continue

    lines.push(`${categoryLabel(category)}:`)
    const detailed = places.slice(0, LOCATIONS_IN_DETAIL)
    const rest = places.slice(LOCATIONS_IN_DETAIL)

    for (const place of detailed) {
      lines.push(
        `- ${place.name} — ${place.apartmentCount} ${plural(place.apartmentCount, 'квартира', 'квартиры', 'квартир')}: ` +
          place.rooms
            .map((item) => `${roomsLabel(item.rooms)} ${item.count} шт. от ${millions(item.priceMin)}`)
            .join('; '),
      )
    }

    if (rest.length > 0 && rest.length <= LOCATIONS_NAMED) {
      lines.push(`- и ещё: ${rest.map((place) => place.name).join(', ')}`)
    } else if (rest.length > LOCATIONS_NAMED) {
      const named = rest.slice(0, LOCATIONS_NAMED).map((place) => place.name).join(', ')
      lines.push(
        `- и ещё ${rest.length} ${plural(rest.length, 'локация', 'локации', 'локаций')}: ${named} и другие — ` +
          'полный список смотри через list_projects, наизусть не додумывай.',
      )
    }

    // Пол цены — по направлению, а не по каталогу: как только появится
    // коммерция или участки, общий минимум придёт от склада, а прозвучит
    // как цена квартиры.
    lines.push(
      `- дешевле ${millions(Math.min(...places.map((place) => place.priceMin)))} в направлении ` +
        `«${categoryLabel(category)}» нет ничего: не обещай поискать дешевле, этого нет.`,
    )
  }

  return [
    '# Локации каталога',
    '',
    'Это весь географический охват агентства, собранный из базы прямо сейчас, по направлениям. Другой локации у нас нет:',
    '',
    lines.join('\n'),
    '',
    'Локация относится к тому направлению, под заголовком которого она стоит, и ни к какому другому. ' +
      'Цены одного направления ничего не говорят про другое.',
    'Города и районы, которых нет в этом перечне, не называй, не предлагай и не упоминай как «варианты рядом».',
    'Здесь только места — города и районы, а не названия ЖК. Про конкретный жилой комплекс этот перечень ' +
      'не говорит ничего: спросили про ЖК — проверь через list_projects, а не по этим строкам.',
    'Описанием проекта этот перечень тоже не является. Он отвечает на вопрос «в каких городах вы работаете», ' +
      'а не на вопрос «что это за комплекс»: улиц, дворов, транспорта, школ и класса жилья здесь нет. ' +
      'Спросили, где стоит дом и что вокруг, — иди в search_knowledge; назвать город из этой строки ' +
      'и на этом закончить нельзя.',
    'Цены здесь — «от», по каждой комнатности отдельно. Сравнивая локации, сверяйся именно с ними и по той же ' +
      'комнатности: там, где дешевле студии, однокомнатные могут быть дороже. Не пиши «там дешевле», не сравнив числа.',
    'Перечень отвечает на вопрос «где мы работаем и что там вообще есть». Поиск он не заменяет никогда: ' +
      'на запрос про квартиры всё равно вызови search_apartments — даже когда по перечню уже видно, что ' +
      'под условия ничего не подходит. Человек должен увидеть карточки ближайшей альтернативы, а не только текст.',
  ].join('\n')
}

function contactLine(context: PromptContext): string {
  if (context.leadCaptured) {
    return 'Контакт уже оставлен и передан менеджеру. Больше телефон не проси — просто продолжай помогать с подбором.'
  }
  if (!context.apartmentsShown) {
    return 'Подборку ты ещё не показывал, поэтому просить имя и телефон рано — сначала принеси пользу.'
  }
  const left = Math.max(context.contactThreshold - context.messagesSinceApartments, 0)
  if (left > 0) {
    return `Подборка показана, но человек обсуждал её всего ${context.messagesSinceApartments} ${plural(context.messagesSinceApartments, 'раз', 'раза', 'раз')}. Подожди ещё ${left} ${plural(left, 'его сообщение', 'его сообщения', 'его сообщений')}, прежде чем предлагать звонок менеджера.`
  }
  return 'Подборка показана, человек её обсуждает — сейчас уместно предложить звонок менеджера и попросить имя и телефон. Один раз: если откажется, продолжай помогать.'
}

const MONTHS = [
  'января',
  'февраля',
  'марта',
  'апреля',
  'мая',
  'июня',
  'июля',
  'августа',
  'сентября',
  'октября',
  'ноября',
  'декабря',
]

function formatDate(date: Date): string {
  const month = MONTHS[date.getMonth()] ?? ''
  return `${date.getDate()} ${month} ${date.getFullYear()} года`
}
