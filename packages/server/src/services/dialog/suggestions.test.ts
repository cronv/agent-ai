import { describe, expect, it } from 'vitest'

import { catalogStems, looksBroken, pickSuggestions } from './suggestions.js'

/**
 * Кнопки быстрых ответов — единственное место, где текст модели попадает
 * человеку не как реплика ассистента, а как его собственные слова. Поэтому
 * проверяется и то, что выбрасывается, и то, что остаётся: лишняя строгость
 * оставляет посетителя без кнопок, а лишняя мягкость — с «Пкомплексами».
 */

/** Каталог боевых данных: семь ЖК и их районы. */
const CATALOG = [
  'ЖК «Школьный» («Альянс»)',
  'ЖК «Космос» (Домодедово)',
  'ЖК «Красная горка» (Подольск)',
  'ЖК «Серебро»',
  'Подольск',
  'Домодедово',
  'Пушкинский',
]

describe('suggest_replies: кнопки быстрых ответов', () => {
  it('пропускает короткие реплики и режет всё, что кнопкой быть не может', () => {
    expect(pickSuggestions(['Покажи подешевле', 'Другой район', 'Хочу посмотреть'])).toEqual([
      'Покажи подешевле',
      'Другой район',
      'Хочу посмотреть',
    ])

    // Кавычки и маркеры списка модель добавляет от себя — на кнопке они лишние.
    expect(pickSuggestions(['«Покажи подешевле»', '— Другой район'])).toEqual(['Покажи подешевле', 'Другой район'])

    // А вот кавычки вокруг названия ЖК — часть реплики, и снимать их нельзя.
    expect(pickSuggestions(['Покажи квартиры в «Школьном»', 'Другой район'])).toEqual([
      'Покажи квартиры в «Школьном»',
      'Другой район',
    ])

    // Повтор в другом регистре — это одна и та же кнопка.
    expect(pickSuggestions(['Подешевле', 'подешевле', 'Другой район'])).toEqual(['Подешевле', 'Другой район'])
  })

  it('длинный вариант выбрасывает, а не обрезает', () => {
    const long = 'Расскажите подробнее про условия ипотеки в этом жилом комплексе'
    expect(pickSuggestions([long, 'Подешевле', 'Другой район'])).toEqual(['Подешевле', 'Другой район'])
  })

  it('меньше двух пригодных вариантов — кнопок нет вовсе', () => {
    // Одинокая кнопка читается как единственный допустимый ответ,
    // а поле ввода рядом с ней — как декорация.
    expect(pickSuggestions(['Подешевле'])).toEqual([])
    expect(pickSuggestions('не массив')).toEqual([])
    expect(pickSuggestions([1, 2, 3])).toEqual([])
  })

  it('берёт не больше четырёх: дальше это уже меню, а не подсказка', () => {
    expect(pickSuggestions(['Раз', 'Два', 'Три', 'Четыре', 'Пять'])).toHaveLength(4)
  })

  it('не зовёт посетителя в прошлое', () => {
    const today = new Date('2026-07-29T12:00:00Z')

    // Живой случай: на подборку со сдачей в июне 2025 модель предложила
    // «Быстрее, в 2024-м».
    expect(pickSuggestions(['Быстрее, в 2024-м', 'Покажи подешевле', 'Другой район'], today)).toEqual([
      'Покажи подешевле',
      'Другой район',
    ])

    // Текущий и будущие годы — нормальная реплика.
    expect(pickSuggestions(['Сдача в 2026 году', 'Готов ждать до 2028-го'], today)).toEqual([
      'Сдача в 2026 году',
      'Готов ждать до 2028-го',
    ])

    // Месяц без года — это ближайший будущий, запрещать его нечем.
    expect(pickSuggestions(['Хочу к июню', 'Другой район'], today)).toEqual(['Хочу к июню', 'Другой район'])

    // После отбраковки осталась одна кнопка — значит кнопок нет.
    expect(pickSuggestions(['Сдача в 2024-м', 'Ключи в 2025 году', 'Другой район'], today)).toEqual([])
  })
})

describe('битые надписи', () => {
  it('выбрасывает реплику с явно испорченным словом', () => {
    // Живой случай: заказчик получил кнопку «Покажи еще Пкомплексы».
    expect(looksBroken('Покажи ещё Пкомплексы')).toBe(true)
    // Заглавная посреди слова, латиница вперемешку с кириллицей, залипшая клавиша.
    expect(looksBroken('ПоКажи подешевле')).toBe(true)
    expect(looksBroken('Пoкажи подешевле')).toBe(true)
    expect(looksBroken('Подешевлеее')).toBe(true)
    // Слово без единой гласной.
    expect(looksBroken('Пкжи прщ')).toBe(true)
    // Незакрытая кавычка — половина названия.
    expect(looksBroken('Покажи квартиры в «Школьном')).toBe(true)
  })

  it('не трогает нормальную русскую речь', () => {
    for (const text of [
      'Покажи подешевле',
      'Другой район',
      'Хочу посмотреть',
      'Сравнить с «Космосом»',
      'Что со сдачей',
      'Ждать до 2028-го',
      'Ближе к МКАД',
      'Взгляд на здание',
      'Мне подходит',
      'Trade-in берёте',
    ]) {
      expect(looksBroken(text), text).toBe(false)
    }
  })

  it('битую реплику выбрасывает целиком, а не чинит', () => {
    expect(pickSuggestions(['Покажи ещё Пкомплексы', 'Покажи подешевле', 'Другой район'])).toEqual([
      'Покажи подешевле',
      'Другой район',
    ])
  })
})

describe('названия каталога с заглавной буквы', () => {
  it('поднимает регистр у склонённого названия ЖК и района', () => {
    expect(pickSuggestions(['Показать квартиры в школьном', 'Сравнить с космосом'], new Date(), CATALOG)).toEqual([
      'Показать квартиры в Школьном',
      'Сравнить с Космосом',
    ])

    expect(pickSuggestions(['Другой район, не подольск', 'Хочу в домодедово'], new Date(), CATALOG)).toEqual([
      'Другой район, не Подольск',
      'Хочу в Домодедово',
    ])
  })

  it('у многословного названия поднимает только первое слово', () => {
    // «в Красной Горке» — это уже другая ошибка, чем «в красной горке».
    expect(pickSuggestions(['Что есть в красной горке', 'Другой район'], new Date(), CATALOG)).toEqual([
      'Что есть в Красной горке',
      'Другой район',
    ])
  })

  it('не цепляет обычные слова, похожие на названия', () => {
    expect(pickSuggestions(['Покажи космический вид', 'Красивый двор'], new Date(), CATALOG)).toEqual([
      'Покажи космический вид',
      'Красивый двор',
    ])
  })

  it('возвращает «ещё» букву «ё»', () => {
    expect(pickSuggestions(['Покажи еще варианты', 'Другой район'])).toEqual([
      'Покажи ещё варианты',
      'Другой район',
    ])
  })

  it('основа названия — не короче пяти букв', () => {
    expect(catalogStems(['ЖК «Космос» (Домодедово)'])).toEqual(['космо', 'домодедо'])
    // «ЖК» и кавычки основой не становятся, номер корпуса в счёт длины идёт.
    expect(catalogStems(['ЖК «Мишино-2»'])).toEqual(['мишино'])
  })
})
