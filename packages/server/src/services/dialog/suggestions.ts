import { SUGGESTION_MAX, SUGGESTION_MAX_LENGTH, SUGGESTION_MIN } from './tools.js'

/**
 * Реплики для кнопок быстрых ответов: отбраковка и мелкий ремонт.
 *
 *   const options = pickSuggestions(input['options'], today, catalogNames)
 *
 * Всё, что приходит сюда, придумала модель, а уйдёт человеку на кнопку и
 * вернётся в диалог как его собственные слова. Поэтому проверка строгая, а
 * непригодный вариант выбрасывается целиком, а не правится: обрезанная или
 * переписанная кнопка обещает одно, а отправляет другое.
 *
 * ── Почему проверка живёт на сервере, а не только в промпте ─────────────────
 *
 * Заказчик получил под ответом «Показать квартиры в школьном», «Сравнить с
 * космосом» и «Покажи еще Пкомплексы». Надпись короткая, и модель экономит на
 * ней внимание сильнее, чем на абзаце текста, — а ошибка в трёх словах видна
 * лучше всего. Правила в промпте есть (см. `prompt.ts`), но правило — это
 * просьба. Здесь остаётся то, что проверяемо без словаря:
 *
 *   заглавная буква у названий каталога   — восстанавливается;
 *   явно битое слово                      — реплика выбрасывается;
 *   «еще» вместо «ещё»                    — исправляется.
 *
 * Правится только то, где правка не меняет смысла реплики: регистр первой
 * буквы и одна пропущенная «ё». Всё остальное — отбраковка.
 */

/** Гласные русского алфавита. */
const VOWELS = 'аеёиоуыэюя'

/** Согласные. Мягкий и твёрдый знаки сюда не входят: это не звуки. */
const CONSONANTS = 'бвгджзйклмнпрстфхцчшщ'

/**
 * Сочетания согласных, с которых русское слово может начинаться.
 *
 * Список конечный и потому проверяемый: «пк» в нём нет, и «Пкомплексы»
 * ловится ровно этим. Собран щедро — цена ошибки несимметрична: лишняя пара
 * в списке пропустит одну битую кнопку, недостающая — выбросит исправную.
 */
const INITIAL_CLUSTERS = new Set([
  'бж', 'бз', 'бл', 'бр',
  'вб', 'вв', 'вг', 'вд', 'вж', 'вз', 'вк', 'вл', 'вм', 'вн', 'вп', 'вр', 'вс', 'вт', 'вх', 'вц', 'вч', 'вш', 'вщ',
  'гл', 'гн', 'гр',
  'дв', 'дж', 'дз', 'дл', 'дн', 'др',
  'жв', 'жг', 'жд', 'жм', 'жн', 'жр',
  'зв', 'зг', 'зд', 'зж', 'зл', 'зм', 'зн', 'зр',
  'кв', 'кл', 'кн', 'кр', 'кс', 'кт',
  'лг', 'лж',
  'мг', 'мз', 'мк', 'мл', 'мн', 'мс', 'мх', 'мц', 'мч', 'мщ',
  'нр',
  'пл', 'пн', 'пр', 'пс', 'пт', 'пф', 'пх', 'пч', 'пш',
  'рв', 'рж', 'рт',
  'сб', 'св', 'сг', 'сд', 'сж', 'сз', 'ск', 'сл', 'см', 'сн', 'сп', 'ср', 'ст', 'сх', 'сц', 'сч', 'сш', 'сщ',
  'тв', 'тк', 'тл', 'тм', 'тр', 'тщ',
  'фл', 'фр', 'фт',
  'хв', 'хл', 'хм', 'хн', 'хр',
  'цв',
  'чв', 'чт',
  'шв', 'шк', 'шл', 'шм', 'шн', 'шп', 'шр', 'шт',
  'щу',
])

/** Слово короче — судить о нём по буквам бессмысленно: это предлог или частица. */
const MIN_JUDGED_WORD = 4

/**
 * Столько согласных подряд в русском слове не встречается.
 * Пять ещё бывает («бодрствовать»), шесть — уже нет.
 */
const MAX_CONSONANT_RUN = 6

/**
 * Явно испорченное слово.
 *
 * Все проверки — про написание, а не про смысл: словаря русского языка здесь
 * нет и быть не может. Поэтому ловится то, чего в правильно написанном слове
 * не бывает вовсе, — и молча пропускается всё остальное.
 */
export function looksBroken(text: string): boolean {
  // Незакрытая кавычка: «Покажи квартиры в «Школьном». Название в кавычках
  // требуется правилами, и половина пары на кнопке видна сразу.
  const open = (text.match(/«/g) ?? []).length
  const close = (text.match(/»/g) ?? []).length
  if (open !== close) return true

  for (const word of text.split(/[^\p{L}]+/u)) {
    if (word === '' || word.length < MIN_JUDGED_WORD) continue

    const cyrillic = /^[а-яёА-ЯЁ]+$/u.test(word)
    const latin = /^[a-zA-Z]+$/u.test(word)

    // Кириллица и латиница внутри одного слова: «Пoкaжи» с латинскими «o» и «a».
    if (!cyrillic && !latin) return true

    // Заглавная буква в середине: «ПКомплексы», «покаЖи». Аббревиатуру целиком
    // из заглавных («ЖК», «МЦД») это не задевает.
    if (word !== word.toUpperCase() && /\p{Lu}/u.test(word.slice(1))) return true

    // Одна буква трижды подряд — след залипшей клавиши, а не слово.
    if (/(\p{L})\1\1/u.test(word)) return true

    if (!cyrillic) continue
    const lower = word.toLowerCase()

    // Русское слово без единой гласной — не слово.
    if (![...lower].some((letter) => VOWELS.includes(letter))) return true

    if (consonantRun(lower) >= MAX_CONSONANT_RUN) return true

    // Аббревиатуру по буквам не судят: «МКАД» и «МЦД» начинаются с сочетаний,
    // которых у обычного слова не бывает, и это не ошибка.
    if (word === word.toUpperCase()) continue

    // Начало, невозможное для русского слова: «пкомплексы», «тмашина».
    const first = lower[0] ?? ''
    const second = lower[1] ?? ''
    if (CONSONANTS.includes(first) && CONSONANTS.includes(second) && !INITIAL_CLUSTERS.has(first + second)) {
      return true
    }
  }

  return false
}

/** Самая длинная цепочка согласных подряд. */
function consonantRun(lower: string): number {
  let longest = 0
  let current = 0
  for (const letter of lower) {
    if (CONSONANTS.includes(letter)) {
      current += 1
      if (current > longest) longest = current
    } else {
      current = 0
    }
  }
  return longest
}

/**
 * Основы названий каталога, по которым узнаётся склонённое слово.
 *
 *   catalogStems(['ЖК «Школьный» («Альянс»)', 'Подольск'])
 *   // → ['школьн', 'альян', 'подоль']
 *
 * Кнопка пишется живой речью, и название в ней стоит в косвенном падеже:
 * «в школьном», «с космосом». Сравнивать целиком нечего, поэтому от названия
 * остаётся основа — все буквы, кроме двух последних, но не короче пяти.
 * Пять — не круглое число: на четырёх «косм» начинает цеплять «космический»,
 * а «крас» — «красивый», и кнопка получает заглавную букву посреди фразы.
 *
 * Слово «ЖК», кавычки и скобки убираются, короткие слова («2», «горка» в
 * «Красная горка») основой не становятся: у многословного названия с заглавной
 * буквы пишется только первое слово, и лишняя основа сделала бы «Красной Горке».
 */
export function catalogStems(names: readonly string[]): string[] {
  const stems = new Set<string>()
  for (const name of names) {
    for (const raw of name.split(/[^\p{L}\p{N}-]+/u)) {
      const word = raw.replace(/^-+|-+$/g, '').toLowerCase()
      if (word.length < 5 || word === 'жк' || !/^[а-яё]/u.test(word)) continue
      stems.add(word.slice(0, Math.max(5, word.length - 2)))
    }
  }
  return [...stems]
}

/**
 * Мелкий ремонт надписи: регистр названий и пропущенная «ё».
 *
 * «Показать квартиры в школьном» → «Показать квартиры в Школьном».
 * Название комплекса со строчной буквы читается как обычное слово, и кнопка
 * перестаёт быть понятной. Выбрасывать её за это жалко — вариантов и так
 * два-четыре, а меньше двух означает, что кнопок не будет вовсе.
 *
 * Кавычки вокруг названия не расставляются: угадать, где кончается название,
 * без разбора фразы нельзя, а лишняя кавычка на кнопке хуже её отсутствия.
 * Кавычки остаются правилом промпта.
 */
export function repairSuggestion(text: string, stems: readonly string[]): string {
  return text.replace(/\p{L}+/gu, (word) => {
    // «еще» — единственная пропущенная «ё», которую можно вернуть, не гадая:
    // слова «еще» в русском языке нет.
    if (word === 'еще') return 'ещё'
    if (word === 'Еще') return 'Ещё'

    if (word.length < 5 || !/^[а-яё]/u.test(word)) return word
    return stems.some((stem) => word.startsWith(stem)) ? word[0]!.toUpperCase() + word.slice(1) : word
  })
}

/**
 * Зовёт ли реплика в прошлое.
 *
 * На подборку со сдачей в июне 2025 модель предложила кнопку «Быстрее,
 * в 2024-м» — при том, что на дворе 2026-й. Дата в системном контексте есть,
 * но на кнопки она не распространяется: модель считает год от собственных
 * представлений о «сейчас». Отсюда проверка здесь, а не только словами
 * в промпте: год в реплике сверяется с настоящим календарём.
 *
 * Сверяется именно год: месяц без года («Хочу к июню») означает ближайший
 * будущий, и запрещать его нельзя.
 */
export function mentionsPastYear(text: string, today: Date): boolean {
  const current = today.getFullYear()
  for (const match of text.matchAll(/\b(19|20)\d{2}\b/g)) {
    if (Number.parseInt(match[0], 10) < current) return true
  }
  return false
}

/**
 * Приводит то, что прислала модель, к списку пригодных для кнопки реплик.
 *
 * Реплика с прошедшим годом выбрасывается целиком, а не правится: «Быстрее,
 * в 2024-м» без года превращается в «Быстрее», и это уже другая реплика.
 * Так же и с битым словом: «Покажи еще Пкомплексы» без «Пкомплексов» —
 * не реплика, а огрызок.
 *
 * `catalog` — названия ЖК и районов из базы; по ним восстанавливается
 * заглавная буква. Пустой список просто выключает эту правку.
 */
export function pickSuggestions(raw: unknown, today: Date = new Date(), catalog: readonly string[] = []): string[] {
  const stems = catalogStems(catalog)
  const seen = new Set<string>()
  const options: string[] = []

  for (const item of toArray(raw)) {
    if (typeof item !== 'string') continue
    const trimmed = unwrap(item)
    if (trimmed === '' || trimmed.length > SUGGESTION_MAX_LENGTH) continue
    if (mentionsPastYear(trimmed, today)) continue
    if (looksBroken(trimmed)) continue
    const text = repairSuggestion(trimmed, stems)
    const key = text.toLowerCase()
    if (seen.has(key)) continue
    seen.add(key)
    options.push(text)
    if (options.length === SUGGESTION_MAX) break
  }

  return options.length >= SUGGESTION_MIN ? options : []
}

/**
 * Снимает маркер списка и кавычки, в которые модель обернула всю реплику.
 *
 *   '— «Покажи подешевле»'          → 'Покажи подешевле'
 *   'Показать квартиры в «Школьном»' → без изменений
 *
 * Кавычки снимаются только парой и только тогда, когда внутри их больше нет.
 * Прежняя правка срезала любую кавычку с конца — и живая реплика «Покажи
 * квартиры в «Школьном»» превращалась в «Покажи квартиры в «Школьном» с
 * открытой кавычкой и без закрывающей. Название в кавычках теперь требуется
 * правилами, так что этот случай стал обычным, а не редким.
 */
function unwrap(item: string): string {
  const text = item.trim().replace(/^[-–—•*]+\s*/u, '').trim()
  const inner = text.slice(1, -1)
  if (text.length > 2 && /^["'«]/u.test(text) && /["'»]$/u.test(text) && !/["'«»]/u.test(inner)) {
    return inner.trim()
  }
  return text
}

/** Одиночное значение приводится к списку. */
function toArray(value: unknown): unknown[] {
  if (Array.isArray(value)) return value
  if (value === undefined || value === null || value === '') return []
  return [value]
}
