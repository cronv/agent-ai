/**
 * Кнопки быстрых ответов.
 *
 * Варианты придумывает модель и только модель: на клиенте их взять неоткуда, а
 * разбирать готовый ответ по разделителям — гадание, которое рассыпается на
 * первом же неожиданном абзаце. Поэтому реплики приходят структурно, отдельным
 * вызовом инструмента, и виджет рисует ровно то, что модель посчитала уместным
 * продолжением разговора.
 *
 * Ограничения длины и количества продублированы в `execute.ts`: описание
 * инструмента — это просьба, а не гарантия.
 */
export const SUGGESTION_MIN = 2
export const SUGGESTION_MAX = 4

/**
 * Предел длины варианта. Это кнопка в окне шириной 420 пикселей: «Покажи
 * подешевле» — 17 символов, «Хочу посмотреть квартиру» — 24. Всё, что длиннее,
 * не обрезается, а выбрасывается: обрезанная кнопка врёт о том, что отправит.
 */
export const SUGGESTION_MAX_LENGTH = 44

