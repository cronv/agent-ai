/** Инструменты, которые ходят за данными. Их число ограничено настройкой `max_tool_calls`. */
export const DATA_TOOLS: ToolDefinition[] = [
  searchApartmentsTool,
  listProjectsTool,
  searchKnowledgeTool,
  saveLeadTool,
]

/** Все инструменты одним списком — именно он уходит в запрос к модели. */
export const DIALOG_TOOLS: ToolDefinition[] = [...DATA_TOOLS, suggestRepliesTool]

/**
 * Набор инструментов для одного запроса.
 *
 * Кнопки выключены настройкой — инструмента в списке нет вовсе. Модель не
 * должна знать про возможность, которой не будет: иначе она пишет «выберите
 * вариант ниже», а под ответом пусто.
 */
export function dialogTools(quickReplies: boolean): ToolDefinition[] {
  return quickReplies ? DIALOG_TOOLS : DATA_TOOLS
}
