import { describe, expect, it } from 'vitest'

import { districtFromComplex, humanizePlace } from './domclick.js'

/**
 * Район у ДомКлика вычисляется, а не читается: отдельного тега для него нет.
 * Здесь — все семь ЖК боевой выгрузки NDV.RU, ровно с теми названиями
 * и адресами, которые лежат в базе заказчика.
 */

const REAL_COMPLEXES: [name: string, address: string, district: string][] = [
  ['ЖК «Космос» (Домодедово)', 'Домодедовский городской округ. ул. Жуковского, д. 4, корп. 1-7', 'Домодедово'],
  ['ЖК «Берег»', 'Химки городской округ. ул. Береговая, д. 1А, 2, 5, 6, 8, 10', 'Химки'],
  ['ЖК «Мишино-2»', 'Химки городской округ. ул. Озерная, ЖК Мишино-2, корп. 5, 6, 7, 8, 9, 10', 'Химки'],
  ['ЖК «Красная горка» (Подольск)', 'Подольск городской округ. ул. Садовая, д. 14', 'Подольск'],
  ['ЖК «Школьный» («Альянс»)', 'Подольск городской округ. ул. Школьная, д. 41, 43', 'Подольск'],
  ['ЖК «Серебро»', 'Пушкинский район. Ярославское ш., 35 километр, корп. 1, 2, 3', 'Пушкинский'],
  [
    'ЖК «Восточный» (Звенигород)',
    'Одинцовский район. микрорайон Восточный, 3-й микрорайон, 1-3, 7, 9-10, 13 корп.',
    'Звенигород',
  ],
]

describe('districtFromComplex', () => {
  it.each(REAL_COMPLEXES)('%s → %s', (name, address, district) => {
    expect(districtFromComplex(name, address)).toBe(district)
  })

  it('уточнение в скобках названия важнее адреса', () => {
    // ЖК «Восточный» административно в Одинцовском районе, но ищут его
    // как Звенигород — и в названии стоит именно он.
    expect(districtFromComplex('ЖК «Восточный» (Звенигород)', 'Одинцовский район. микрорайон Восточный')).toBe(
      'Звенигород',
    )
    expect(districtFromComplex(null, 'Одинцовский район. микрорайон Восточный')).toBe('Одинцово')
  })

  it('второе название ЖК в скобках районом не считается', () => {
    expect(districtFromComplex('ЖК «Школьный» («Альянс»)', null)).toBeNull()
    expect(districtFromComplex('ЖК «Волга» (2 очередь)', null)).toBeNull()
  })

  it('без адреса и без подсказки в названии район остаётся пустым', () => {
    expect(districtFromComplex('ЖК «Берег»', null)).toBeNull()
    expect(districtFromComplex(null, null)).toBeNull()
  })

  it('населённый пункт может стоять во второй части адреса', () => {
    expect(districtFromComplex(null, 'г.о. Домодедово. ул. Жуковского, д. 4')).toBe('Домодедово')
  })
})

describe('humanizePlace', () => {
  it('снимает слова административного деления', () => {
    expect(humanizePlace('Химки городской округ')).toBe('Химки')
    expect(humanizePlace('Подольск городской округ')).toBe('Подольск')
    expect(humanizePlace('городское поселение Яхрома')).toBe('Яхрома')
    expect(humanizePlace('г. Долгопрудный')).toBe('Долгопрудный')
    expect(humanizePlace('Московская область')).toBe('Московская')
  })

  it('разворачивает прилагательное в название города', () => {
    expect(humanizePlace('Домодедовский городской округ')).toBe('Домодедово')
    expect(humanizePlace('Одинцовский район')).toBe('Одинцово')
    // -инский однозначно не разворачивается: Пушкино или Пушкин — не понять.
    expect(humanizePlace('Пушкинский район')).toBe('Пушкинский')
  })

  it('не трогает составные названия', () => {
    expect(humanizePlace('Старый Оскол')).toBe('Старый Оскол')
    expect(humanizePlace('Наро-Фоминский городской округ')).toBe('Наро-Фоминский')
  })

  it('кусок улицы местом не считает', () => {
    expect(humanizePlace('ул. Жуковского')).toBeNull()
    expect(humanizePlace('д. 4, корп. 1-7')).toBeNull()
    expect(humanizePlace('Ярославское ш., 35 километр')).toBeNull()
    expect(humanizePlace('микрорайон Восточный')).toBeNull()
    expect(humanizePlace('городской округ')).toBeNull()
    expect(humanizePlace('   ')).toBeNull()
  })
})
